/**
 * 標題「只顯示一行」用的寬度估算（2026-08-18 新增）。
 *
 * ── 為什麼需要這個 ────────────────────────────────────────
 * 中文標題換行的位置是瀏覽器決定的，它只會避開標點，不會顧慮語意。
 * 於是「史特拉斯堡｜聖誕市集飲食記」很容易被斷成
 *
 *     史特拉斯堡｜聖
 *     誕市集飲食記
 *
 * ——在「｜」後面斷開，把一個詞從中間切成兩半。這在排版上是壞的：
 * 標題是一個整體，它應該像招牌一樣一眼讀完，不是一段要換行的內文。
 *
 * 最直接的解法是「不准換行」，但只做 white-space: nowrap 的話，
 * 長標題會被切掉尾巴（變成「史特拉斯堡｜聖誕市…」）。所以這裡多做一步：
 * **先算出這個標題有多寬，再讓字級自動縮到剛好放得下一行。**
 *
 * ── 怎麼算 ────────────────────────────────────────────────
 * 回傳值的單位是 em（相對於字級本身）。中文字是全形，一個字約等於
 * 1em；英文字母大約半個。把每個字加起來就是「這個標題需要幾 em 的寬度」。
 *
 * 有了這個數字，CSS 就能算出字級：
 *
 *     字級 = 容器寬度 ÷ 標題的 em 寬度
 *
 * 再用 clamp() 夾在「原本的字級」與「一個下限」之間：短標題維持原本大小，
 * 長標題自動縮小，縮到下限還放不下的極端情況才用「…」收尾。
 * 實作在 global.css 的 .title-fit。
 */

/**
 * 全形字：中日韓文字、假名、諺文、全形標點與全形英數。
 * 這一類字在襯線字體裡的字面寬度約等於一個字級（1em）。
 */
const FULLWIDTH_RE =
	/[\u1100-\u115F\u2E80-\u303E\u3041-\u33FF\u3400-\u4DBF\u4E00-\u9FFF\uA000-\uA4CF\uAC00-\uD7A3\uF900-\uFAFF\uFE30-\uFE6F\uFF00-\uFF60\uFFE0-\uFFE6]/;

export function titleFitEm(title: string): number {
	let em = 0;

	for (const char of title ?? "") {
		if (FULLWIDTH_RE.test(char)) em += 1; // 中文、全形標點
		else if (char === " ") em += 0.28; // 空格
		else if (/[A-Z0-9]/.test(char)) em += 0.62; // 大寫與數字
		else if (/[a-z]/.test(char)) em += 0.5; // 小寫
		else if (/[iljt.,;:'’!|]/.test(char)) em += 0.28; // 細字母與標點
		else em += 0.55; // 其他
	}

	// 標題有 0.01～0.02em 的字距，再加一點安全邊界，
	// 免得算出來剛好等於容器寬度、最後一個字被「…」吃掉。
	em *= 1.06;

	// 太短的標題（例如兩個字）不要因為除出來的字級太大而爆版，
	// 給一個下限；CSS 那邊本來就有 max 夾住，這裡只是避免除以 0。
	return Math.max(2, Number(em.toFixed(2)));
}
